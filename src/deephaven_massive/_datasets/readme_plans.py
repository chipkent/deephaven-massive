"""The README's plans table: which of Massive's plans include the data the tutorial reads.

The README's tutorial reads a few datasets, and a reader needs to know which plan each one
needs. Rather than name a plan beside each example, the README holds one table, generated here
from the plan tables of Massive's own documentation pages (`Provenance.plans`). Its cells are
the ones each dataset's page shows, made by the same function (`column_reference.plan_cell`),
so the README and the dataset pages never disagree, and both follow every refresh of Massive's
documentation.

The only hand input is `ROWS`: which of Massive's pages document the data each row names. It
names datasets and pages, never a plan: the columns are whatever plans those pages list, in
the order they list them, so a plan Massive adds or renames reaches the README at the next
refresh. A row whose page the refresh no longer has, or that isn't a page of its dataset,
stops the render with `ValueError` instead of leaving the row out.

`scripts/render_reference.py` rewrites the table between the README's two marker lines
(`with_plans_table`), and a parity test fails when the committed README differs, so a refresh
that changes a plan table lands with the regenerated README. The README is this module's only
reader. It is pure: it reads only its arguments and writes nothing.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Final

from deephaven_massive._datasets.column_reference import (
    COMMAND,
    dataset_urls,
    page_name,
    plan_cell,
    table_row,
)

if TYPE_CHECKING:
    from deephaven_massive._datasets.catalog import Catalog
    from deephaven_massive._massive import Provenance

__all__ = [
    "PLANS_TABLE_END",
    "PLANS_TABLE_START",
    "ROWS",
    "PlansRow",
    "plans_table",
    "with_plans_table",
]


@dataclass(frozen=True)
class PlansRow:
    """One row of the README's plans table: some data the tutorial reads.

    Attributes:
        label: The row's name in the table, in the README's words, such as `"Bars, history"`.
        dataset: The dataset's dotted name, such as `"stocks.bars"`; the label links its page.
        urls: The URLs of the vendor pages, as the refresh fetched them, whose plan tables give
            the row's cells. A dataset documented on several pages, such as bars read from
            REST and streamed, names only the pages of the data the tutorial reads.
    """

    label: str
    dataset: str
    urls: tuple[str, ...]


_REST: Final = "https://massive.com/docs/rest/stocks"
"""The prefix of Massive's REST pages for stocks."""

ROWS: Final = (
    PlansRow(
        "Bars, history",
        "stocks.bars",
        (
            f"{_REST}/aggregates/custom-bars.md",
            f"{_REST}/aggregates/daily-market-summary.md",
        ),
    ),
    PlansRow(
        "Minute bars, streamed",
        "stocks.bars",
        ("https://massive.com/docs/websocket/stocks/aggregates-per-minute.md",),
    ),
    PlansRow(
        "Previous day bar",
        "stocks.previous_day_bar",
        (f"{_REST}/aggregates/previous-day-bar.md",),
    ),
    PlansRow("News", "reference.news", (f"{_REST}/news.md",)),
    PlansRow("Snapshots", "stocks.snapshots", (f"{_REST}/snapshots/full-market-snapshot.md",)),
)
"""The data the README's tutorial reads, in the order its examples first read it."""

PLANS_TABLE_START: Final = (
    f"<!-- The plans table is generated by `{COMMAND}`; do not edit it by hand. -->"
)
"""The line before the README's generated plans table."""

PLANS_TABLE_END: Final = "<!-- End of the generated plans table. -->"
"""The line after the README's generated plans table."""

_GUIDE: Final = (
    "How recent the data is on each of Massive's plans, and how far back its history goes, as "
    "Massive's pages state them. An empty cell is a plan the page doesn't list."
)
"""The paragraph above the table."""


def plans_table(catalog: Catalog, provenance: Provenance) -> str:
    """Render the README's plans table.

    Args:
        catalog: The catalog, which holds each row's dataset.
        provenance: The vendor pages' plan tables, by URL, and each source's pages.

    Returns:
        The guide, a blank line, and the table, ending in one newline: a header of **Data**
        and every plan the rows' pages list, then one row per entry of `ROWS`, its label
        linked to its dataset's page and each cell `plan_cell` of its pages for that plan.

    Raises:
        KeyError: If a row's dataset isn't in the catalog.
        ValueError: If a row's URL isn't one of its dataset's vendor pages, or has no plan
            tables.
    """
    pages = []
    for row in ROWS:
        spec = catalog.by_name[row.dataset]
        own = dataset_urls(spec, provenance)
        for url in row.urls:
            if url not in own:
                raise ValueError(f"{url} is not a vendor page of {row.dataset}")
            if url not in provenance.plans:
                raise ValueError(f"{url} has no plan tables in the refreshed documentation")
        pages.append([(url, provenance.plans[url]) for url in row.urls])
    plans = list(
        dict.fromkeys(t.plan for row_pages in pages for _, page in row_pages for t in page.plans)
    )
    lines = [_GUIDE, "", table_row(["Data", *plans]), table_row(["---"] * (len(plans) + 1))]
    for row, row_pages in zip(ROWS, pages, strict=True):
        link = f"[{row.label}](docs/datasets/{page_name(catalog.by_name[row.dataset])}#plans)"
        lines.append(table_row([link, *(plan_cell(plan, row_pages) for plan in plans)]))
    return "\n".join(lines) + "\n"


def with_plans_table(page: str, catalog: Catalog, provenance: Provenance) -> str:
    """Return the README with its generated plans table replaced by `plans_table()`.

    Args:
        page: The README's text. Everything outside its two marker lines is kept as written.
        catalog: The catalog, for `plans_table`.
        provenance: The vendor pages' plan tables, for `plans_table`.

    Returns:
        The README as `scripts/render_reference.py` writes it.

    Raises:
        ValueError: If the page lacks `PLANS_TABLE_START`, or `PLANS_TABLE_END` after it, or
            as `plans_table` raises.
    """
    start = page.find(PLANS_TABLE_START)
    end = page.find(PLANS_TABLE_END, max(start, 0))
    if start < 0 or end < 0:
        raise ValueError(
            "the README needs the lines PLANS_TABLE_START and PLANS_TABLE_END around its "
            "generated plans table"
        )
    head = page[: start + len(PLANS_TABLE_START)]
    return f"{head}\n\n{plans_table(catalog, provenance)}\n{page[end:]}"
